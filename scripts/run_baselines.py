"""Run the Tier-0 baselines through purged walk-forward CV and write the leaderboard.

This is a harness smoke test, not a real result: it runs against synthetic OHLCV data,
since no real BTC history has been fetched into data/raw/ yet (btcpred.data.fetch's
functions are implemented and tested, but pulling ~8 years of history is a separate,
deliberate step -- see README). Re-run this script against real fetched data once
`btcpred fetch` is wired up and executed; until then, treat these numbers as "the
harness works," not "here is the model performance."
"""

from __future__ import annotations

from collections.abc import Callable
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
from btcpred.features.build import build_feature_matrix
from btcpred.models.baselines import (
    BuyAndHoldRegressor,
    LagOneLinearRegressor,
    MeanReturnRegressor,
    NaiveZeroRegressor,
)
from btcpred.validation.metrics import directional_accuracy, mae, r_squared, rmse
from btcpred.validation.splitters import PurgedWalkForwardSplit

HORIZON = 1
N_SPLITS = 5
REPORTS_PATH = Path("reports/results.md")

BASELINES = {
    "naive_zero": lambda: NaiveZeroRegressor(),
    "mean_return": lambda: MeanReturnRegressor(),
    "buy_and_hold": lambda: BuyAndHoldRegressor(),
    "lag_one_linear": lambda: LagOneLinearRegressor(),
}


def _make_synthetic_ohlcv(n: int = 1500, seed: int = 0) -> pd.DataFrame:
    idx = pd.date_range("2018-01-01", periods=n, freq="D", tz="UTC")
    rng = np.random.default_rng(seed)
    log_returns = rng.normal(0.0002, 0.03, n)
    close = 5_000 * np.exp(np.cumsum(log_returns))
    high = close * (1 + rng.uniform(0, 0.015, n))
    low = close * (1 - rng.uniform(0, 0.015, n))
    open_ = close * (1 + rng.normal(0, 0.005, n))
    volume = rng.uniform(1_000, 10_000, n)
    return pd.DataFrame(
        {"open": open_, "high": high, "low": low, "close": close, "volume": volume}, index=idx
    )


def _evaluate_model(
    model_fn: Callable[[], Any],
    X: pd.DataFrame,
    y: pd.Series,
    splitter: PurgedWalkForwardSplit,
) -> dict[str, float]:
    fold_metrics = []
    for train_idx, test_idx in splitter.split(X):
        model = model_fn()
        model.fit(X.iloc[train_idx], y.iloc[train_idx])
        preds = model.predict(X.iloc[test_idx])
        y_test = y.iloc[test_idx].to_numpy()
        fold_metrics.append(
            {
                "rmse": rmse(y_test, preds),
                "mae": mae(y_test, preds),
                "r2": r_squared(y_test, preds),
                "directional_accuracy": directional_accuracy(y_test, preds),
            }
        )
    return {k: float(np.mean([fm[k] for fm in fold_metrics])) for k in fold_metrics[0]}


def main() -> None:
    ohlcv = _make_synthetic_ohlcv()
    matrix = build_feature_matrix(ohlcv, horizons=(HORIZON,))
    feature_cols = [c for c in matrix.columns if not c.startswith(("y_reg_", "y_clf_"))]
    matrix = matrix.dropna(subset=[*feature_cols, f"y_reg_h{HORIZON}"])

    X = matrix[feature_cols]
    y = matrix[f"y_reg_h{HORIZON}"]
    splitter = PurgedWalkForwardSplit(n_splits=N_SPLITS, purge=HORIZON, embargo=HORIZON)

    results = {name: _evaluate_model(fn, X, y, splitter) for name, fn in BASELINES.items()}
    leaderboard = pd.DataFrame(results).T.sort_values("rmse")

    REPORTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORTS_PATH.write_text(
        "# Baseline leaderboard (harness smoke test -- synthetic data)\n\n"
        "Generated by `scripts/run_baselines.py`. This validates the walk-forward CV "
        "harness end-to-end on synthetic OHLCV data. It is **not** a real performance "
        "result -- rerun against real fetched BTC data once available.\n\n"
        f"{_to_markdown_table(leaderboard)}\n"
    )
    print(leaderboard)


def _to_markdown_table(df: pd.DataFrame) -> str:
    """Render a DataFrame as a GitHub-flavored markdown table (avoids a tabulate dependency)."""
    header = f"| model | {' | '.join(df.columns)} |"
    separator = f"|{'---|' * (len(df.columns) + 1)}"
    rows = [
        f"| {name} | {' | '.join(f'{value:.6f}' for value in row)} |"
        for name, row in zip(df.index, df.to_numpy(), strict=True)
    ]
    return "\n".join([header, separator, *rows])


if __name__ == "__main__":
    main()
